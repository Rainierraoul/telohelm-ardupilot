"""Write protocol/TASK-TEXTS.md: everything each paper 3 task tells the learner, with its contract fingerprint.

Run from paper3/:  .venv/bin/python protocol/task_texts.py
The file is regenerated at the freeze and its hash recorded; the paper's Appendix A is taken from it.
"""
from dataclasses import fields
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from ardupilot import pack as P  # noqa: E402

TASKS = ('reach', 'avoid', 'orbit', 'land', 'reach3d')

lines = ['# What each paper 3 task tells the learner', '',
         'Generated by `protocol/task_texts.py` from `ardupilot/pack.py`. The shared text below is part of every '
         "task's goal text. The goal values each scenario fills in (targets, radii, limits) come from the scenario "
         'generator and are not listed here.', '', '## Shared goal text', '', P.SHARED_GOAL.strip(), '']
for name in TASKS:
    task, pub = P.TASKS[name], P.PACKS[name].public
    lines += [f'## {name}', '', f'Contract fingerprint: `{pub.fingerprint({})}`', '',
              f'Command fields: {", ".join(task.fields)}. Decision every {task.tick_s:g} simulated second(s). '
              f'Extra readings: {", ".join(task.extra_readings) or "none"}.', '']
    for f in fields(task):
        v = getattr(task, f.name)
        if isinstance(v, str) and f.name not in ('name', 'pack_id', 'success'):
            text = v.replace(P.SHARED_GOAL, '[shared goal text] ').strip()
            lines += [f'- **{f.name}**: {text}']
    lines += ['']
(ROOT / 'protocol' / 'TASK-TEXTS.md').write_text('\n'.join(lines))
print('wrote protocol/TASK-TEXTS.md')
